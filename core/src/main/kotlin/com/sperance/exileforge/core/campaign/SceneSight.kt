package com.sperance.exileforge.core.campaign

/**
 * Что видно в изометрии сцены: камера смотрит из-за правого нижнего угла карты, скала встаёт над своей клеткой и
 * закрывает стоящее позади неё. Одно правило для мест объектов, места выхода и полупрозрачных стен сцены: место, где пол вокруг
 * лишь с четырёх сторон, прятало бы сундук или выход за скалой по диагонали.
 */
object SceneSight {
    /** Клетки перед клеткой по ходу камеры: скала в них закрывает то, что на ней стоит. */
    private val FRONT = listOf(1 to 1, 2 to 1, 1 to 2, 2 to 2)

    /** Ничто перед клеткой [x], [y] её не закрывает: в клетках [FRONT] нет скалы ([rock]). */
    fun inView(x: Int, y: Int, rock: (x: Int, y: Int) -> Boolean): Boolean = FRONT.none { (dx, dy) -> rock(x + dx, y + dy) }
}
