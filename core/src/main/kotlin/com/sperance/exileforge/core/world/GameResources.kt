package com.sperance.exileforge.core.world

import kotlinx.coroutines.flow.Flow

/**
 * Ресурсы игры с сервера: контент, словарь и иконки. Проверка обновлений ждёт их готовности на холодном старте,
 * чтобы не делить с ними сеть, а по возвращении в игру сперва сверяет их с манифестом и только потом спрашивает GitHub.
 */
interface GameResources {
    /** Контент разобран, словарь и иконки прочитаны - с устройства или с сервера. */
    val ready: Flow<Boolean>

    /** Сверка с манифестом сервера: сменившееся качается заново; отказ тих - ресурсы остаются прежними. */
    suspend fun recheck()
}
