package com.sperance.exileforge.core.campaign

/**
 * Что видно в изометрии сцены (3.95.3): камера смотрит из-за правого нижнего угла карты, скала встаёт над своей клеткой и
 * закрывает стоящее позади неё. Одно правило для мест объектов, места выхода и полупрозрачных стен сцены: прежде объекты
 * ставились там, где пол вокруг был лишь с четырёх сторон, и сундук или выход прятался за скалой по диагонали.
 */
object SceneSight {
    /** Клетки перед клеткой по ходу камеры: скала в них закрывает то, что на ней стоит. */
    private val FRONT = listOf(1 to 1, 2 to 1, 1 to 2, 2 to 2)

    /** Ничто перед клеткой [x], [y] её не закрывает: в клетках [FRONT] нет скалы ([rock]). */
    fun inView(x: Int, y: Int, rock: (x: Int, y: Int) -> Boolean): Boolean = FRONT.none { (dx, dy) -> rock(x + dx, y + dy) }

    /** Клетки, скала в которых закрыла бы [cell]. */
    fun screening(cell: Cell): List<Cell> = FRONT.map { (dx, dy) -> Cell(cell.x + dx, cell.y + dy) }
}
